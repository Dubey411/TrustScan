import { Metadata } from 'next';
import ResultsClient from './ResultsClient';

interface Props {
  params: Promise<{ id: string }>;
}

export async function generateMetadata({ params }: Props): Promise<Metadata> {
  const { id } = await params;
  return {
    title: 'Safety Analysis Report | Verified by TrustScan AI',
    description: 'Detailed fraud analysis report for a suspicious document or link. View security findings and risk scores generated by TrustScan AI.',
    alternates: {
      canonical: `/results/${id}`,
    },
    robots: {
      index: false, // Don't index shared dynamic results to avoid thin content
      follow: true,
    }
  };
}

export default async function SharedResultsPage({ params }: Props) {
  const { id } = await params;
  return <ResultsClient id={id} />;
}
